// Fallback coordinate offset for custom or unknown locations
export const getGeoCoordinates = (districtName, upazilaName, unionName, wardStr, villageName) => {
  // Resilient district resolution
  let districtKey = districtName;
  if (!DISTRICTS_DATA[districtKey] && districtName) {
    const cleanDist = districtName.trim().toLowerCase();
    if (DISTRICT_ENGLISH_MAP[cleanDist]) {
      districtKey = DISTRICT_ENGLISH_MAP[cleanDist];
    } else {
      for (const d of Object.keys(DISTRICTS_DATA)) {
        if (d.includes(districtName) || districtName.includes(d)) {
          districtKey = d;
          break;
        }
      }
    }
  }

  const districtObj = DISTRICTS_DATA[districtKey];
  if (!districtObj) {
    return [24.7471, 90.4203]; // Default Mymensingh
  }

  let lat = districtObj.lat;
  let lon = districtObj.lon;

  // Resilient upazila resolution
  let upazilaObj = null;
  if (upazilaName && districtObj.upazilas) {
    if (districtObj.upazilas[upazilaName]) {
      upazilaObj = districtObj.upazilas[upazilaName];
    } else {
      for (const [uName, uObj] of Object.entries(districtObj.upazilas)) {
        if (uName.includes(upazilaName) || upazilaName.includes(uName)) {
          upazilaObj = uObj;
          break;
        }
      }
    }
  }

  if (upazilaObj) {
    lat = upazilaObj.lat;
    lon = upazilaObj.lon;
  }

  // Deterministic micro adjustment for Union
  if (unionName) {
    let hash = 0;
    for (let i = 0; i < unionName.length; i++) {
      hash = (hash << 5) - hash + unionName.charCodeAt(i);
      hash |= 0;
    }
    const unionAngle = (Math.abs(hash) % 360) * (Math.PI / 180);
    const unionDist = 0.006 + ((Math.abs(hash) % 10) * 0.0006); // ~700m - 1.2km
    lat += Math.sin(unionAngle) * unionDist;
    lon += Math.cos(unionAngle) * unionDist;
  }

  // Micro adjustments for Ward (Ward 1 to 9 creates hyperlocal spatial position)
  if (wardStr) {
    const bnToEn = { '১': 1, '২': 2, '৩': 3, '৪': 4, '৫': 5, '৬': 6, '৭': 7, '৮': 8, '৯': 9 };
    let wardNum = null;
    for (const [bn, en] of Object.entries(bnToEn)) {
      if (wardStr.includes(bn)) {
        wardNum = en;
        break;
      }
    }
    if (!wardNum) {
      const match = wardStr.match(/\d+/);
      if (match) wardNum = parseInt(match[0], 10);
    }

    if (wardNum) {
      const angle = (wardNum * (360 / 9)) * (Math.PI / 180);
      const radius = 0.0035; // ~380 meters
      lat += Math.sin(angle) * radius;
      lon += Math.cos(angle) * radius;
    }
  }

  // Micro adjustments for Village / Para (~150m-300m inside the ward boundary)
  if (villageName && typeof villageName === 'string') {
    let vHash = 0;
    for (let i = 0; i < villageName.length; i++) {
      vHash = (vHash << 5) - vHash + villageName.charCodeAt(i);
      vHash |= 0;
    }
    const vAngle = (Math.abs(vHash) % 360) * (Math.PI / 180);
    const vDist = 0.0018 + ((Math.abs(vHash) % 10) * 0.00015);
    lat += Math.sin(vAngle) * vDist;
    lon += Math.cos(vAngle) * vDist;
  }

  return [parseFloat(lat.toFixed(5)), parseFloat(lon.toFixed(5))];
};

// Calculate distance between two lat/lon pairs in km
function haversineDistance(lat1, lon1, lat2, lon2) {
  const R = 6371; // Earth radius in km
  const dLat = (lat2 - lat1) * Math.PI / 180;
  const dLon = (lon2 - lon1) * Math.PI / 180;
  const a = 
    Math.sin(dLat/2) * Math.sin(dLat/2) +
    Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) * 
    Math.sin(dLon/2) * Math.sin(dLon/2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1-a));
  return R * c;
}

